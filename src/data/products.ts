// PalaComparer data model

import type { Locale } from "@/i18n/locales";

export type Sport = "padel" | "tenis";

export type PadelShape = "redonda" | "lagrima" | "diamante" | "hibrida";
export type Level = "principiante" | "intermedio" | "avanzado" | "profesional";
export type PlayStyle = "control" | "potencia" | "polivalente";

export interface PadelSpecs {
  shape: PadelShape;
  weight: string; // e.g. "360-375 g"
  balance: "bajo" | "medio" | "alto";
  core: string; // EVA Soft, EVA Hard, FOAM, Multieva...
  faces: string; // Carbono 12K, Fibra de vidrio...
  surface: string; // rugosa/lisa
  hardness: "blanda" | "media" | "dura";
}

export interface TenisSpecs {
  headSize: number; // sq in
  weightStrung: number; // grams
  length: number; // cm
  stringPattern: string; // "16x19"
  stiffness: number; // RA
  balancePoints: number; // pts from butt, e.g. 320 mm
  swingweight: number;
}

export interface Product {
  id: string; // slug
  sport: Sport;
  brand: string;
  model: string;
  year: number;
  price: number; // EUR PVP approx
  image: string; // path or URL
  level: Level[];
  style: PlayStyle[]; // padel; for tenis derived
  player?: string; // pro player associated
  padel?: PadelSpecs;
  tenis?: TenisSpecs;
  /** Descripción en español (idioma base del catálogo). */
  description: string;
  /** Traducción al inglés. Si falta, se cae a la española. */
  descriptionEn?: string;
}

/** Descripción del producto en el locale pedido (con fallback a ES). */
export function getDescription(p: Product, locale: Locale): string {
  return locale === "en" ? p.descriptionEn ?? p.description : p.description;
}

